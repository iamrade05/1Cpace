BY_ID = {e['id']: e for e in EXERCISES}
_IMPACT_RANK = {k: i for i, k in enumerate(IMPACT)}
_LEVEL_RANK = {k: i for i, k in enumerate(LEVELS)}


def select(region=None, category=None, level=None, goal=None, exclude=(), max_impact='high'):
    """Exercises suitable for a member: level is the highest level offered,
    exclude is the member's condition flags, max_impact caps impact."""
    out = []
    for e in EXERCISES:
        if region and region not in e['regions']:
            continue
        if category and e['category'] != category:
            continue
        if level and _LEVEL_RANK[e['level']] > _LEVEL_RANK[level]:
            continue
        if goal and goal not in e['goals']:
            continue
        if set(e['avoid']) & set(exclude):
            continue
        if _IMPACT_RANK[e['impact']] > _IMPACT_RANK[max_impact]:
            continue
        out.append(e)
    return out


def alternatives(exercise_id, exclude=(), max_impact='high'):
    """Swap candidates in the same category that share a region and carry none of the excluded flags."""
    base = BY_ID[exercise_id]
    return [e for e in select(category=base['category'], exclude=exclude, max_impact=max_impact)
            if e['id'] != exercise_id and set(e['regions']) & set(base['regions'])]
